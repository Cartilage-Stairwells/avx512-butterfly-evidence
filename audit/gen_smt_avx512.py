#!/usr/bin/env python3
"""Generator for the AVX-512 engine-op SMT scripts (32-bit-lane schedule).

Emits standalone SMT-LIB2 files modeling the production engine ops of
src/vector/avx512.rs instruction-for-instruction at the 32-bit-lane level,
using ONLY intrinsic semantics that are pinned empirically on real
AVX-512F+DQ silicon by tests/avx512_intrinsic_semantics.rs:

  - _mm512_add_epi32 / _mm512_sub_epi32      : wrapping 32-bit lane arith
  - _mm512_cmpge_epu32_mask(a,b)             : bit l set iff a[l] >=u b[l]
  - _mm512_cmplt_epu32_mask(a,b)             : bit l set iff a[l] <u  b[l]
  - _mm512_mask_add_epi32(src,k,a,b)         : k[l] set -> a+b else src
  - _mm512_mask_sub_epi32(src,k,a,b)         : k[l] set -> a-b else src
  - _mm512_mask_blend_epi32(k,a,b)           : k[l] set -> b[l] else a[l]
  - _mm512_mul_epu32(a,b)                    : 64-bit lane i =
        u32(32-bit lane 2i of a) * u32(32-bit lane 2i of b)
  - _mm512_movehdup_ps on cast int           : out[2i]=out[2i+1]=in[2i+1]
  - masked vmovshdup (asm), mask k           : out[2i]= k[2i]? in[2i+1] :
        src[2i]; out[2i+1]= k[2i+1]? in[2i+2] : src[2i+1]
        (engine uses k=EVENS=0x5555 so odd lanes keep src)

Claim format: the scripts assert the NEGATION of the conjunction over all
16 lanes of the lane-identity claim; Z3 must answer unsat. Each mutation
control flips exactly one schedule detail and must answer sat.

Constants: BABYBEAR_P = 0x78000001, MU = 0x88000001 = P^-1 mod 2^32
(subtraction-form REDC), R = 2^32.
"""
import argparse, sys

P32 = "#x78000001"
MU32 = "#x88000001"
R64 = "#x0000000100000000"
PR64 = "#x7800000100000000"  # P * R (exact 64-bit)
BV32 = "(_ BitVec 32)"
BV64 = "(_ BitVec 64)"

def zext(e, w=64):  # zero-extend a 32-bit expr to 64
    assert w == 64
    return f"((_ zero_extend 32) {e})"

def lo32(e): return f"((_ extract 31 0) {e})"
def hi32(e): return f"((_ extract 63 32) {e})"


def lane_mul_defs(b, w, i, tag, mu=MU32, sched_p=P32, correct=True, keep=None):
    """One butterfly pair (even butterfly e=2i, odd butterfly o=2i+1).

    Returns (defs, claims). Models mont_mul_16's even/odd product +
    masked-merge dataflow for output lanes 2i (even butterfly) and
    2i+1 (odd butterfly).
    """
    e, o = 2*i, 2*i+1
    d = []
    d.append(f"(define-fun prod_evn_{tag}{i} () {BV64} (bvmul {zext(b[e])} {zext(w[e])}))")
    d.append(f"(define-fun prod_odd_{tag}{i} () {BV64} (bvmul {zext(b[o])} {zext(w[o])}))")
    d.append(f"(define-fun q_evn_{tag}{i} () {BV64} (bvmul {zext(lo32(f'prod_evn_{tag}{i}'))} {zext(mu)}))")
    d.append(f"(define-fun q_odd_{tag}{i} () {BV64} (bvmul {zext(lo32(f'prod_odd_{tag}{i}'))} {zext(mu)}))")
    d.append(f"(define-fun q_p_evn_{tag}{i} () {BV64} (bvmul {zext(lo32(f'q_evn_{tag}{i}'))} {zext(sched_p)}))")
    d.append(f"(define-fun q_p_odd_{tag}{i} () {BV64} (bvmul {zext(lo32(f'q_odd_{tag}{i}'))} {zext(sched_p)}))")
    d.append(f"(define-fun prod_hi_{tag}{e} () {BV32} {hi32(f'prod_evn_{tag}{i}')})")
    d.append(f"(define-fun prod_hi_{tag}{o} () {BV32} {hi32(f'prod_odd_{tag}{i}')})")
    d.append(f"(define-fun q_p_hi_{tag}{e} () {BV32} {hi32(f'q_p_evn_{tag}{i}')})")
    d.append(f"(define-fun q_p_hi_{tag}{o} () {BV32} {hi32(f'q_p_odd_{tag}{i}')})")
    for l in (e, o):
        d.append(f"(define-fun u_{tag}{l} () Bool (bvult prod_hi_{tag}{l} q_p_hi_{tag}{l}))")
        if correct:
            d.append(f"(define-fun res_{tag}{l} () {BV32} (bvadd (bvsub prod_hi_{tag}{l} q_p_hi_{tag}{l}) (ite u_{tag}{l} {P32} #x00000000)))")
        else:
            d.append(f"(define-fun res_{tag}{l} () {BV32} (bvsub prod_hi_{tag}{l} q_p_hi_{tag}{l}))")
    claims = []
    claims.append(
        f"(and (bvult res_{tag}{e} {P32}) "
        f"(= (bvadd (bvmul {zext(f'res_{tag}{e}')} {R64}) (bvmul {zext(lo32(f'q_evn_{tag}{i}'))} {zext(P32)})) "
        f"(bvadd prod_evn_{tag}{i} (ite u_{tag}{e} {PR64} #x0000000000000000))))")
    claims.append(
        f"(and (bvult res_{tag}{o} {P32}) "
        f"(= (bvadd (bvmul {zext(f'res_{tag}{o}')} {R64}) (bvmul {zext(lo32(f'q_odd_{tag}{i}'))} {zext(P32)})) "
        f"(bvadd prod_odd_{tag}{i} (ite u_{tag}{o} {PR64} #x0000000000000000))))")
    if keep is not None:
        claims = [c for idx, c in enumerate(claims) if idx in keep]
    return d, claims


def header(name, desc):
    return f"""; {name} — {desc}
; Generated by audit/gen_smt_avx512.py. Semantics pinned empirically on
; AVX-512F+DQ silicon (tests/avx512_intrinsic_semantics.rs).
(set-option :produce-models true)
(set-logic QF_BV)
"""


def gen_mul(mutate=None, pairs=(0, 1, 2, 3, 4, 5, 6, 7), split=None):
    s = [header("mont_mul_16 (32-bit-lane schedule)",
                "16-lane Montgomery multiply, production relaned schedule")]
    for i in pairs:
        for l in (2*i, 2*i+1):
            s.append(f"(declare-const b{l} {BV32})")
            s.append(f"(declare-const w{l} {BV32})")
            s.append(f"(assert (bvult b{l} {P32}))")
            s.append(f"(assert (bvult w{l} {P32}))")
    mu = MU32 if mutate != "wrong_mu" else "#x88000002"
    sched_p = P32 if mutate != "wrong_p" else "#x78000003"
    correct = mutate != "no_underflow"
    defs, claims = [], []
    for i in pairs:
        d, c = lane_mul_defs([f"b{l}" for l in range(16)], [f"w{l}" for l in range(16)], i, "",
                             mu=mu, sched_p=sched_p, correct=correct, keep=split)
        defs += d; claims += c
    s += defs
    s.append("(assert (not (and " + " ".join(claims) + ")))")
    s.append("(check-sat)\n(exit)")
    return "\n".join(s) + "\n"


def gen_add(mutate=None):
    s = [header("avx512_add", "16-lane modular add, schedule as written")]
    for l in range(16):
        s.append(f"(declare-const a{l} {BV32})")
        s.append(f"(declare-const b{l} {BV32})")
        s.append(f"(assert (bvult a{l} {P32}))")
        s.append(f"(assert (bvult b{l} {P32}))")
    claims = []
    for l in range(16):
        s.append(f"(define-fun sum{l} () {BV32} (bvadd a{l} b{l}))")
        cmp = "bvuge" if mutate != "cmpgt" else "bvugt"
        s.append(f"(define-fun ge{l} () Bool ({cmp} sum{l} {P32}))")
        s.append(f"(define-fun res{l} () {BV32} (bvsub sum{l} (ite ge{l} {P32} #x00000000)))")
        # claim: res < P and res + (ge? P:0) = a + b  (exact, 64-bit)
        claims.append(
            f"(and (bvult res{l} {P32}) "
            f"(= (bvadd {zext(f'res{l}')} (ite ge{l} {zext(P32)} #x0000000000000000)) "
            f"(bvadd {zext(f'a{l}')} {zext(f'b{l}')})))")
    s.append("(assert (not (and " + " ".join(claims) + ")))")
    s.append("(check-sat)\n(exit)")
    return "\n".join(s) + "\n"


def gen_sub(mutate=None):
    s = [header("avx512_sub", "16-lane modular sub, schedule as written")]
    for l in range(16):
        s.append(f"(declare-const a{l} {BV32})")
        s.append(f"(declare-const b{l} {BV32})")
        s.append(f"(assert (bvult a{l} {P32}))")
        s.append(f"(assert (bvult b{l} {P32}))")
    claims = []
    for l in range(16):
        s.append(f"(define-fun raw{l} () {BV32} (bvsub a{l} b{l}))")
        s.append(f"(define-fun adj{l} () {BV32} (bvadd raw{l} {P32}))")
        s.append(f"(define-fun ge{l} () Bool (bvuge a{l} b{l}))")
        # production blend: k=ge set -> SECOND arg (raw); else first (adj).
        # Mutation blend_swapped: k set -> adj.
        pick = f"(ite ge{l} raw{l} adj{l})" if mutate != "blend_swapped" else f"(ite ge{l} adj{l} raw{l})"
        s.append(f"(define-fun res{l} () {BV32} {pick})")
        # claim: res < P and res + b = a + (ge ? 0 : P)  [exact, 64-bit]
        claims.append(
            f"(and (bvult res{l} {P32}) "
            f"(= (bvadd {zext(f'res{l}')} {zext(f'b{l}')}) "
            f"(bvadd {zext(f'a{l}')} (ite ge{l} #x0000000000000000 {zext(P32)}))))")
    s.append("(assert (not (and " + " ".join(claims) + ")))")
    s.append("(check-sat)\n(exit)")
    return "\n".join(s) + "\n"


def gen_fused(mutate=None, pairs=(0, 1, 2, 3, 4, 5, 6, 7)):
    s = [header("avx512_radix2_butterfly_32",
                "16-lane fused DIF butterfly: (a+b mod P, ((a-b mod P)*w)*R^-1 mod P)")]
    all_lanes = [l for i in pairs for l in (2*i, 2*i+1)]
    for l in all_lanes:
        s.append(f"(declare-const a{l} {BV32})")
        s.append(f"(declare-const b{l} {BV32})")
        s.append(f"(declare-const w{l} {BV32})")
        s.append(f"(assert (bvult a{l} {P32}))")
        s.append(f"(assert (bvult b{l} {P32}))")
        s.append(f"(assert (bvult w{l} {P32}))")
    claims = []
    # add schedule -> out_a[l]
    for l in all_lanes:
        s.append(f"(define-fun sum{l} () {BV32} (bvadd a{l} b{l}))")
        s.append(f"(define-fun ge_sum{l} () Bool (bvuge sum{l} {P32}))")
        s.append(f"(define-fun out_a{l} () {BV32} (bvsub sum{l} (ite ge_sum{l} {P32} #x00000000)))")
        claims.append(
            f"(and (bvult out_a{l} {P32}) "
            f"(= (bvadd {zext(f'out_a{l}')} (ite ge_sum{l} {zext(P32)} #x0000000000000000)) "
            f"(bvadd {zext(f'a{l}')} {zext(f'b{l}')})))")
        # sub schedule -> diff[l]  (production blend: k=ge_a set -> raw)
        s.append(f"(define-fun raw{l} () {BV32} (bvsub a{l} b{l}))")
        s.append(f"(define-fun adj{l} () {BV32} (bvadd raw{l} {P32}))")
        s.append(f"(define-fun ge_a{l} () Bool (bvuge a{l} b{l}))")
        pick = f"(ite ge_a{l} raw{l} adj{l})" if mutate != "blend_swapped" else f"(ite ge_a{l} adj{l} raw{l})"
        s.append(f"(define-fun diff{l} () {BV32} {pick})")
        # explicit sub claim: the blend output IS (a-b) mod P, canonical —
        # binds the sub schedule inside the fused composition (mutation-
        # checked; without it a broken blend is invisible to the claims).
        claims.append(
            f"(and (bvult diff{l} {P32}) "
            f"(= (bvadd {zext(f'diff{l}')} {zext(f'b{l}')}) "
            f"(bvadd {zext(f'a{l}')} (ite ge_a{l} #x0000000000000000 {zext(P32)}))))")
    # mul schedule on (diff, w): claims speak about res_f_l directly
    mdefs, mclaims = [], []
    for i in pairs:
        d, c = lane_mul_defs([f"diff{l}" for l in range(16)], [f"w{l}" for l in range(16)], i, "f_")
        mdefs += d; mclaims += c
    s += mdefs
    s.append("; out_b[l] := res_f_[l] (the mul schedule result on (diff, w))")
    for l in all_lanes:
        s.append(f"(define-fun out_b{l} () {BV32} res_f_{l})")
    claims += mclaims
    s.append("(assert (not (and " + " ".join(claims) + ")))")
    s.append("(check-sat)\n(exit)")
    return "\n".join(s) + "\n"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("op", choices=["add", "sub", "mul", "fused"])
    ap.add_argument("--mutate", default=None)
    ap.add_argument("--pairs", default=None,
                    help="comma-separated butterfly pair indices (default: all 0-7)")
    ap.add_argument("--split", choices=["even", "odd"], default=None,
                    help="emit only one lane's claim of each pair (conjunction split)")
    args = ap.parse_args()
    pairs = tuple(int(x) for x in args.pairs.split(",")) if args.pairs else tuple(range(8))
    gen = {"add": gen_add, "sub": gen_sub, "mul": gen_mul, "fused": gen_fused}[args.op]
    if args.op == "mul":
        split_keep = {"even": (0,), "odd": (1,), None: None}[args.split]
        sys.stdout.write(gen(args.mutate, pairs=pairs, split=split_keep))
    elif args.op == "fused":
        sys.stdout.write(gen(args.mutate, pairs=pairs))
    else:
        sys.stdout.write(gen(args.mutate))


if __name__ == "__main__":
    main()
