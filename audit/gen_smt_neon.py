#!/usr/bin/env python3
"""Generator for the NEON engine-op SMT scripts (4-lane schedule).

Emits standalone SMT-LIB2 files modeling the production engine ops of
src/vector/neon.rs instruction-for-instruction at the 4-lane level, using
ONLY intrinsic semantics pinned empirically on real Apple Silicon (aarch64,
NEON baseline) by tests/neon_intrinsic_semantics.rs:

  - vaddq_u32 / vsubq_u32 / vadd?/vsub?  : wrapping 32-bit lane arith
  - vcgeq_u32(a,b) / vcge_u32(a,b)       : all-ones lane iff a >=u b
                                           (EQUALITY INCLUDED)
  - vcltq_u32(a,b)                       : all-ones lane iff a <u  b (strict)
  - vbslq_u32(m,a,b) / vbsl              : (m & a) | (~m & b)
  - vand_u32(m,p)                        : per-lane bitwise and
  - vmull_u32(a,b)                       : 64-bit lane = zext32(a)*zext32(b)
  - vmul_u32(a,b)                        : low 32 bits of a*b
  - vmlal_u32(acc,m,p)                   : acc + zext(m)*zext(p), 64-bit
  - vmovn_u64(v)                         : low 32 bits of each 64-bit lane
  - vshrn_n_u64(v,32)                    : low 32 bits of (v >> 32)

Claim format: each script asserts the NEGATION of the conjunction over all
4 lanes of the lane-identity claim; Z3 must answer unsat. Each mutation
control flips exactly one schedule detail and must answer sat.

Claim identities (R = 2^32, all arithmetic exact in 64 bits):

  add lane : out < P  /\  zext(out) + zext(ge?P:0) = zext(a) + zext(b)
             => out = (a+b) mod P canonical (out ≡ a+b, out < P).
  sub lane : out < P  /\  zext(out) + zext(b) = zext(a) + zext(lt?P:0)
             => out = (a-b) mod P canonical.
  mul lane : out < P  /\  zext(out)*R + (ge?P*R:0) = prod + zext(m)*zext(P)
             => out*R ≡ prod (mod P) with out canonical, i.e. out is the
                unique Montgomery reduction a*b*R^-1 mod P (the m and ge
                terms are multiplied by P, so they cannot fudge the
                congruence; the equation is the exact integer identity
                t*R = prod + m*P with t = out + ge*P, which holds iff the
                REDC invariant mp ≡ 0 (mod R) holds for the schedule's
                constants).

Constants: BABYBEAR_P = 0x78000001, BABYBEAR_NEG_INV = 0x77FFFFFF
(= -P^-1 mod 2^32; P*NEG_INV ≡ 0xffffffff (mod 2^32), checked at import),
R = 2^32.

There is NO fused-butterfly SMT script for NEON: the engine has no fused
specialization (recorded decision, src/vector/neon.rs — it delegates to the
generic kernel, so no fused claim exists to verify).
"""
import sys

P32 = "#x78000001"
NEG_INV32 = "#x77ffffff"
R64 = "#x0000000100000000"
PR64 = "#x7800000100000000"  # P * R (exact 64-bit)
ONES32 = "#xffffffff"
ZEROS32 = "#x00000000"
ZERO64 = "#x0000000000000000"
BV32 = "(_ BitVec 32)"
BV64 = "(_ BitVec 64)"

assert (0x78000001 * 0x77FFFFFF) % 2**32 == 2**32 - 1, "NEG_INV premise broken"

def zext(e):
    return f"((_ zero_extend 32) {e})"

HEADER = """; {title}
; Generated by audit/gen_smt_neon.py from src/vector/neon.rs (NeonVectorEngine,
; LANES = 4, lifted verbatim from examples/butterfly_neon.rs per audit D5).
; Intrinsic semantics pinned empirically on aarch64 Apple Silicon by
; tests/neon_intrinsic_semantics.rs. Constants: P = 0x78000001,
; NEG_INV = 0x77FFFFFF (-P^-1 mod 2^32), R = 2^32.
; Expected result: {expected}
(set-option :produce-models true)
(set-logic QF_BV)
"""

def decl_inputs(lanes):
    out = []
    for i in range(lanes):
        out.append(f"(declare-const a{i} {BV32})")
        out.append(f"(declare-const b{i} {BV32})")
        out.append(f"(assert (bvult a{i} {P32}))")
        out.append(f"(assert (bvult b{i} {P32}))")
    return "\n".join(out)

def add_lane(i, cmp="bvuge"):
    return f"""; lane {i}: vaddq_u32(a,b); vsubq_u32(sum,P); vcgeq_u32(sum,P); vbslq_u32(ge, sum_minus_p, sum)
(define-fun sum_{i} () {BV32} (bvadd a{i} b{i}))
(define-fun sum_minus_p_{i} () {BV32} (bvsub sum_{i} {P32}))
(define-fun ge_mask_{i} () {BV32} (ite ({cmp} sum_{i} {P32}) {ONES32} {ZEROS32}))
(define-fun out_{i} () {BV32} (bvor (bvand ge_mask_{i} sum_minus_p_{i}) (bvand (bvnot ge_mask_{i}) sum_{i})))"""

def add_claim(i):
    return (f"(and (bvult out_{i} {P32}) "
            f"(= (bvadd {zext(f'out_{i}')} {zext(f'(ite (bvuge sum_{i} {P32}) {P32} {ZEROS32})')}) "
            f"(bvadd {zext(f'a{i}')} {zext(f'b{i}')})))")

def sub_lane(i, swapped=False):
    first, second = ("diff", "diff_plus_p") if swapped else ("diff_plus_p", "diff")
    return f"""; lane {i}: vsubq_u32(a,b); vaddq_u32(diff,P); vcltq_u32(a,b); vbslq_u32(lt, diff_plus_p, diff)
(define-fun diff_{i} () {BV32} (bvsub a{i} b{i}))
(define-fun diff_plus_p_{i} () {BV32} (bvadd diff_{i} {P32}))
(define-fun lt_mask_{i} () {BV32} (ite (bvult a{i} b{i}) {ONES32} {ZEROS32}))
(define-fun out_{i} () {BV32} (bvor (bvand lt_mask_{i} {first}_{i}) (bvand (bvnot lt_mask_{i}) {second}_{i})))"""

def sub_claim(i):
    return (f"(and (bvult out_{i} {P32}) "
            f"(= (bvadd {zext(f'out_{i}')} {zext(f'b{i}')}) "
            f"(bvadd {zext(f'a{i}')} {zext(f'(ite (bvult a{i} b{i}) {P32} {ZEROS32})')})))")

def mul_lane(i, neg_inv=NEG_INV32, p_mul=None, cond_sub=True, m_zero=False, p_final=None):
    p_mul = p_mul or P32
    m_line = (f"(define-fun m_{i} () {BV32} {ZEROS32})" if m_zero else
              f"(define-fun m_{i} () {BV32} ((_ extract 31 0) (bvmul {zext(f'((_ extract 31 0) prod_{i})')} {zext(neg_inv)})))")
    p_final = p_final or P32
    if not cond_sub:
        return f"""; lane {i}: vmull_u32(a,b); vmovn_u64; vmul_u32(x,NEG_INV); vmlal_u32(prod,m,P);
; vshrn_n_u64(mp,32)  [MUTATION: conditional subtraction dropped]
(define-fun prod_{i} () {BV64} (bvmul {zext(f'a{i}')} {zext(f'b{i}')}))
{m_line}
(define-fun mp_{i} () {BV64} (bvadd prod_{i} (bvmul {zext(f'm_{i}')} {zext(p_mul)})))
(define-fun t_{i} () {BV32} ((_ extract 63 32) mp_{i}))
(define-fun out_{i} () {BV32} t_{i})"""
    return f"""; lane {i}: vmull_u32(a,b); vmovn_u64; vmul_u32(x,NEG_INV); vmlal_u32(prod,m,P);
; vshrn_n_u64(mp,32); vcge_u32(t,P); vand_u32(ge,P); vsub_u32(t,sub)
(define-fun prod_{i} () {BV64} (bvmul {zext(f'a{i}')} {zext(f'b{i}')}))
{m_line}
(define-fun mp_{i} () {BV64} (bvadd prod_{i} (bvmul {zext(f'm_{i}')} {zext(p_mul)})))
(define-fun t_{i} () {BV32} ((_ extract 63 32) mp_{i}))
(define-fun ge_mask_{i} () {BV32} (ite (bvuge t_{i} {P32}) {ONES32} {ZEROS32}))
(define-fun sub_{i} () {BV32} (bvand ge_mask_{i} {p_final}))
(define-fun out_{i} () {BV32} (bvsub t_{i} sub_{i}))"""

def mul_claim(i):
    ge = f"(ite (bvuge t_{i} {P32}) {PR64} {ZERO64})"
    return (f"(and (bvult out_{i} {P32}) "
            f"(= (bvadd (bvmul {zext(f'out_{i}')} {R64}) {ge}) "
            f"(bvadd prod_{i} (bvmul {zext(f'm_{i}')} {zext(P32)}))))")

def emit(fname, title, expected, lanes_code, claims):
    body = HEADER.format(title=title, expected=expected)
    body += decl_inputs(4) + "\n\n"
    body += "\n".join(lanes_code) + "\n\n"
    body += "(assert (not (and\n  " + "\n  ".join(claims) + ")))\n(check-sat)\n(exit)\n"
    with open(fname, "w") as f:
        f.write(body)
    print(f"wrote {fname}")

if __name__ == "__main__":
    lanes = 4
    emit("neon_add_op.smt2", "NeonVectorEngine::add — 4-lane Montgomery add",
         "unsat",
         [add_lane(i) for i in range(lanes)],
         [add_claim(i) for i in range(lanes)])
    emit("neon_sub_op.smt2", "NeonVectorEngine::sub — 4-lane Montgomery sub",
         "unsat",
         [sub_lane(i) for i in range(lanes)],
         [sub_claim(i) for i in range(lanes)])
    emit("neon_mont_mul_vec.smt2", "NeonVectorEngine::mul (neon_mont_mul_vec + neon_reduce_2) — 4-lane Montgomery multiply",
         "unsat",
         [mul_lane(i) for i in range(lanes)],
         [mul_claim(i) for i in range(lanes)])
    # mutations — each flips exactly one schedule detail, must be SAT
    emit("mutation_add_vcgt.smt2", "MUTATION: add with vcgt instead of vcge (equality edge sum==P)",
         "sat", [add_lane(i, cmp="bvugt") for i in range(lanes)],
         [add_claim(i) for i in range(lanes)])
    emit("mutation_sub_bsl_swapped.smt2", "MUTATION: sub with vbsl operands swapped",
         "sat", [sub_lane(i, swapped=True) for i in range(lanes)],
         [sub_claim(i) for i in range(lanes)])
    emit("mutation_redc_wrong_neg_inv.smt2", "MUTATION: REDC with NEG_INV off by one",
         "sat", [mul_lane(i, neg_inv="#x77fffffe") for i in range(lanes)],
         [mul_claim(i) for i in range(lanes)])
    emit("mutation_redc_wrong_p.smt2", "MUTATION: REDC with P off by one in vmlal (output-EQUIVALENT: absorbed by the low word; expected unsat)",
         "unsat", [mul_lane(i, p_mul="#x78000002") for i in range(lanes)],
         [mul_claim(i) for i in range(lanes)])
    emit("mutation_redc_wrong_p_final.smt2", "MUTATION: REDC with P off by one in the final conditional subtraction",
         "sat", [mul_lane(i, p_final="#x78000002") for i in range(lanes)],
         [mul_claim(i) for i in range(lanes)])
    emit("mutation_redc_no_cond_sub.smt2", "MUTATION: REDC without conditional subtraction",
         "sat", [mul_lane(i, cond_sub=False) for i in range(lanes)],
         [mul_claim(i) for i in range(lanes)])
    emit("mutation_redc_m_zero.smt2", "MUTATION: REDC with m forced to zero (skip vmul_u32)",
         "sat", [mul_lane(i, m_zero=True) for i in range(lanes)],
         [mul_claim(i) for i in range(lanes)])
